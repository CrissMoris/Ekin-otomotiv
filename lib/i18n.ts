/** Dile göre adres: Türkçe kökte, İngilizce /en, Arapça /ar altında. */
export function lp(lang: Lang, path: string): string {
  if (lang === "tr") return path;
  return path === "/" ? `/${lang}` : `/${lang}${path}`;
}

/** Aynı sayfanın diğer dildeki adresi. */
export function switchPath(pathname: string, to: Lang): string {
  const m = /^\/(en|ar)(\/.*)?$/.exec(pathname);
  const base = m ? m[2] || "/" : pathname || "/";
  return lp(to, base);
}

